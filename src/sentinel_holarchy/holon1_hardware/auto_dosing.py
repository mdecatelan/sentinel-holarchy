"""
Holon 1: Zero-Weighing ("Dump & Go") Hardware & Product-Driven Stoichiometric Control.
Combines:
  1. Simple Compost Rule of Thumb at input (~1/3 Starchy/Brown Carbon + ~2/3 Green/Algae)
  2. HX711 Load Cells under drum feet (automatic waste tare + auto-water filling valve + EC0 baseline tare)
  3. Passive CaCO3 Mineral Cartridge (shells dissolve strictly on-demand when pH < 6.0)
  4. Stoichiometric Product Tracker: measures VFA formation via differential conductivity
     Delta_EC(t) = EC(t) - EC0 (immune to kitchen salt NaCl) + CO2 off-gas plateau + DO Spike harvest trigger.
"""

from dataclasses import dataclass
from typing import Dict
import math


@dataclass
class DumpAndGoTelemetry:
    """Early maceration & baseline tare signals (t = 0 to 2h)."""
    hx711_gross_waste_kg: float       # Measured automatically when waste is dumped in drum
    motor_current_ma_at_45rpm: float  # Mechanical load indicator
    conductivity_ec_ms_cm: float      # Baseline ionic conductivity EC0 (includes kitchen salt NaCl)
    initial_orp_drop_mv_per_h: float  # Deoxygenation velocity
    initial_ph_drop_per_h: float      # Early acidification slope


class PassiveBufferCartridge:
    """
    Models a refillable porous inox basket filled with 250g of crushed eggshells or oyster shells.
    Because CaCO3 is insoluble at neutral pH (Ksp = 3.3e-9), it cannot overdose the batch:
    it dissolves strictly in proportion to the organic acids produced:
      2 R-COOH + CaCO3(s) -> Ca2+(aq) + 2 R-COO-(aq) + H2O + CO2(g)
    """

    def __init__(self, initial_mass_g: float = 250.0, capacity_g: float = 250.0):
        self.remaining_mass_g = initial_mass_g
        self.capacity_g = capacity_g

    def consume_for_batch(self, vfa_produced_g: float) -> Dict[str, float]:
        """
        Calculates stoichiometric CaCO3 dissolved to neutralize protonated VFAs.
        Approx 0.42 g of CaCO3 dissolves per gram of VFA buffered above pH 5.8.
        """
        needed_g = vfa_produced_g * 0.42
        dissolved_g = min(self.remaining_mass_g, needed_g)
        self.remaining_mass_g = max(0.0, self.remaining_mass_g - dissolved_g)
        fill_pct = (self.remaining_mass_g / self.capacity_g) * 100.0
        batches_left = int(self.remaining_mass_g // max(1.0, needed_g)) if needed_g > 0 else 10

        return {
            "dissolved_this_batch_g": round(dissolved_g, 1),
            "remaining_cartridge_g": round(self.remaining_mass_g, 1),
            "cartridge_level_pct": round(fill_pct, 1),
            "estimated_batches_remaining": batches_left,
            "refill_needed": fill_pct < 15.0
        }


class StoichiometricProductTracker:
    """
    Rigorous product-driven sensor law replacing naive feedstock guessing:
      - Subtracts initial salt conductivity EC0 at t = 0.5h
      - Tracks Delta_EC(t) = EC(t) - EC0 generated by CaCO3 dissolution into Ca2+ + 2 R-COO-
      - Detects Phase 1 completion when d(Delta_EC)/dt -> 0 and CO2 evolution drops to baseline
      - Detects Phase 2 completion via the Dissolved Oxygen rebound ("DO Spike")
    """

    def __init__(self, baseline_ec0_ms_cm: float = 4.0):
        self.ec0 = baseline_ec0_ms_cm

    def estimate_vfa_from_delta_ec(self, current_ec_ms_cm: float, co2_rate_ml_min: float = 0.0) -> Dict[str, float]:
        """
        Each 1.0 mS/cm increase above EC0 corresponds to ~12.2 g/L of calcium carboxylates
        formed by VFA neutralization on the passive CaCO3 cartridge.
        """
        delta_ec = max(0.0, current_ec_ms_cm - self.ec0)
        vfa_from_ec_g_l = delta_ec * 12.2
        acidogenesis_complete = (delta_ec > 1.2) and (co2_rate_ml_min < 8.0)
        return {
            "baseline_ec0_ms_cm": round(self.ec0, 2),
            "delta_ec_ms_cm": round(delta_ec, 2),
            "stoichiometric_vfa_g_l": round(vfa_from_ec_g_l, 2),
            "acidogenesis_plateau_reached": acidogenesis_complete
        }

    @staticmethod
    def detect_do_spike_harvest(do_mg_l: float, d_do_dt: float, time_in_aeration_h: float) -> bool:
        """
        Triggers harvest when bacteria stop respiring VFAs because intracellular PHA saturation
        is reached, causing dissolved oxygen to rebound above 7.8 mg/L ("DO Spike").
        """
        return time_in_aeration_h > 4.0 and do_mg_l >= 7.8 and abs(d_do_dt) < 0.08


class BlindFeedstockInferencer:
    """
    Handles automatic HX711 water dosing and translates the operator's compost rule-of-thumb
    (~1/3 starchy carbon + ~2/3 green peels/algae) into initial simulation states.
    """

    @staticmethod
    def auto_fill_water(hx711_waste_kg: float, target_slurry_ratio: float = 1.5) -> Dict[str, float]:
        water_added_l = round(max(0.5, hx711_waste_kg * target_slurry_ratio), 2)
        total_drum_mass_kg = round(hx711_waste_kg + water_added_l, 2)
        return {
            "detected_waste_kg": round(hx711_waste_kg, 2),
            "auto_water_injected_l": water_added_l,
            "target_hx711_total_kg": total_drum_mass_kg
        }

    @classmethod
    def infer_composition_from_maceration(cls, signals: DumpAndGoTelemetry) -> Dict[str, float]:
        auto_water = cls.auto_fill_water(signals.hx711_gross_waste_kg)
        waste_kg = auto_water["detected_waste_kg"]
        water_l = auto_water["auto_water_injected_l"]

        current_excess = max(0.0, signals.motor_current_ma_at_45rpm - 420.0)
        inferred_dry_fraction = min(0.45, max(0.10, 0.12 + (current_excess / 1200.0)))
        inferred_moisture_pct = (1.0 - inferred_dry_fraction) * 100.0

        intrinsic_water_l = waste_kg * (1.0 - inferred_dry_fraction)
        effective_volume_l = max(0.5, water_l + intrinsic_water_l)

        dry_mass_g = waste_kg * inferred_dry_fraction * 1000.0
        activity_factor = min(1.35, max(0.55, abs(signals.initial_orp_drop_mv_per_h) / 95.0))
        inferred_carbs_g_l = (dry_mass_g * 0.72 * activity_factor) / effective_volume_l

        inferred_n_g_l = max(0.6, min(5.5, 0.45 * signals.conductivity_ec_ms_cm))
        inferred_cn_ratio = inferred_carbs_g_l / inferred_n_g_l
        inferred_odd_ratio = min(0.40, max(0.18, 0.42 - 0.006 * inferred_cn_ratio))

        return {
            "detected_waste_kg": round(waste_kg, 2),
            "auto_water_injected_l": round(water_l, 2),
            "effective_liquid_volume_l": round(effective_volume_l, 2),
            "inferred_moisture_pct": round(inferred_moisture_pct, 1),
            "inferred_carbohydrates_g_l": round(inferred_carbs_g_l, 1),
            "inferred_nitrogen_g_l": round(inferred_n_g_l, 2),
            "inferred_cn_ratio": round(inferred_cn_ratio, 1),
            "inferred_odd_vfa_ratio": round(inferred_odd_ratio, 3)
        }
